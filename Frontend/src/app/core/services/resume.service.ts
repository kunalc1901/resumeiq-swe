import { HttpClient, HttpEvent, HttpHeaders } from '@angular/common/http';
import { Injectable } from '@angular/core';
import { Observable } from 'rxjs';
import { ApiService } from './api.service';
import { ResumeRecord } from '../models/resume.model';

const RESUME_URL = '/resume';

/** Response of POST /resume/upload (presigned S3 PUT target). */
export interface ResumeUploadUrl {
  upload_url: string;
  key: string;
  file_name: string;
  content_type: string;
  expires_in: number;
}

@Injectable({
  providedIn: 'root',
})
export class ResumeService {
  constructor(
    private apiService: ApiService,
    private http: HttpClient,
  ) {}

  /**
   * Method to get all resumes of the logged-in user, newest first. The user is
   * derived from the token on the API side.
   * @returns
   */
  getResumes(): Observable<ResumeRecord[]> {
    return this.apiService.get(RESUME_URL);
  }

  /**
   * Requests a short-lived presigned URL for uploading a resume directly to
   * S3. The S3 key is generated by the API and scoped to the current user.
   * @param file The PDF selected by the user
   */
  getUploadUrl(file: File): Observable<ResumeUploadUrl> {
    return this.apiService.post(`${RESUME_URL}/upload`, {
      file_name: file.name,
      // The dialog only accepts PDFs; normalize the MIME type so the signed
      // Content-Type always matches what the upload sends.
      content_type: 'application/pdf',
      file_size: file.size,
    });
  }

  /**
   * Uploads the file straight to S3 using the presigned URL. Progress events
   * are emitted so the UI can show a progress bar.
   * @param uploadUrl Presigned S3 PUT URL
   * @param file The file to upload
   */
  uploadToS3(uploadUrl: string, file: File): Observable<HttpEvent<unknown>> {
    return this.http.put(uploadUrl, file, {
      headers: new HttpHeaders({
        'Content-Type': 'application/pdf',
      }),
      reportProgress: true,
      observe: 'events',
      // S3 returns an empty body; avoid Angular trying to parse it as JSON.
      responseType: 'text',
    });
  }

  /**
   * Saves the resume in MongoDB after the S3 upload succeeded. The API checks
   * that the object exists before creating the document.
   * @param key S3 object key returned by getUploadUrl
   * @param fileName Original file name for display
   */
  createResume(key: string, fileName: string): Observable<ResumeRecord> {
    return this.apiService.post(RESUME_URL, { key, file_name: fileName });
  }
}
